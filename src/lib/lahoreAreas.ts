/** Nearest listed area to the given coordinates (for syncing the dropdown to the pin). */
export function nearestArea(lat: number, lng: number): LahoreArea {
  let best = LAHORE_AREAS[0];
  let bestDist = Infinity;
  for (const area of LAHORE_AREAS) {
    const dLat = area.lat - lat;
    const dLng = (area.lng - lng) * Math.cos((lat * Math.PI) / 180);
    const dist = dLat * dLat + dLng * dLng;
    if (dist < bestDist) {
      bestDist = dist;
      best = area;
    }
  }
  return best;
}

